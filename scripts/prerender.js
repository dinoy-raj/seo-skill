#!/usr/bin/env node
// Pre-render a JavaScript site to static HTML: one file per route, so every address paints before any script runs and
// crawlers, link unfurlers and AI agents get the full page with its own head. Also writes sitemap.xml.
//
// Works with any client-rendered site (React, Vue, Svelte, plain JS): it opens each route in headless Chromium, waits for
// the page to settle and saves the DOM. Head tags the app sets at runtime (title, meta, canonical, JSON-LD) are captured.
//
//   node prerender.js --root dist --site https://example.com                 # discover routes by following links from /
//   node prerender.js --root . --site https://example.com --routes / /about /apps
//   node prerender.js --server http://localhost:4173 --out dist --site https://example.com   # use a running server
//   node prerender.js --config prerender.config.json
//
// Options (CLI or JSON config with the same names in camelCase):
//   --root DIR        folder to serve from disk (default .). Unknown document paths get --fallback (SPA shell).
//   --server URL      fetch pages from this server instead of serving --root.
//   --out DIR         where to write (default: --root).
//   --site URL        production origin for sitemap.xml (required for the sitemap).
//   --routes ...      routes to render. Without it, routes are discovered by following same-origin links from "/".
//   --fallback FILE   SPA shell for routes with no file (default index.html).
//   --root-selector S only replace the contents of this element (e.g. #root) in the template, keep the template's
//                     own scripts and head otherwise. Without it, the whole document is saved.
//   --wait-for S      CSS selector that must exist before the snapshot (default: none; waits for network idle).
//   --dirs            write /about as about/index.html instead of about.html (hosts without clean-URL support).
//   --exclude ...     route prefixes to skip during discovery (default /design /admin).
//   --no-sitemap      don't write sitemap.xml.
//
// After rendering, the client must hydrate the markup instead of replacing it (hydrateRoot, createSSRApp, hydrate()).
// Re-run after every content change: stale markup causes hydration mismatches, which throw the markup away.
// Needs Playwright: `npm i -D playwright` (or a global install). Chromium: `npx playwright install chromium`.
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');

const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json',
  '.webp': 'image/webp', '.avif': 'image/avif', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.gif': 'image/gif',
  '.svg': 'image/svg+xml', '.ico': 'image/x-icon', '.woff2': 'font/woff2', '.woff': 'font/woff', '.txt': 'text/plain', '.xml': 'application/xml' };
const GENERATED = '<!-- Generated by prerender.js. Edit the source and re-run it instead of editing this file. -->';

function parseArgs(argv) {
  const o = { root: '.', fallback: 'index.html', exclude: ['/design', '/admin'], sitemap: true, dirs: false };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    const many = () => { const v = []; while (argv[i + 1] && !argv[i + 1].startsWith('--')) v.push(argv[++i]); return v; };
    if (k === '--config') Object.assign(o, JSON.parse(fs.readFileSync(argv[++i], 'utf8')));
    else if (k === '--routes') o.routes = many();
    else if (k === '--exclude') o.exclude = many();
    else if (k === '--dirs') o.dirs = true;
    else if (k === '--no-sitemap') o.sitemap = false;
    else if (k.startsWith('--')) o[k.slice(2).replace(/-(\w)/g, (_, c) => c.toUpperCase())] = argv[++i];
  }
  o.root = path.resolve(o.root); o.out = path.resolve(o.out || o.root);
  if (o.site) o.site = o.site.replace(/\/$/, '');
  return o;
}

const routeFile = (o, route) => route === '/' ? path.join(o.out, 'index.html')
  : o.dirs ? path.join(o.out, route.slice(1), 'index.html') : path.join(o.out, route.slice(1) + '.html');

(async () => {
  const o = parseArgs(process.argv.slice(2));
  const ORIGIN = o.server ? o.server.replace(/\/$/, '') : 'http://prerender.test';
  const shellPath = path.join(o.root, o.fallback);
  // Read the template once, before anything is overwritten, so re-runs always start from the source shell.
  // JSON-LD is dropped from the shell because apps append it at runtime; a shell that is itself a previous output (out = root)
  // would otherwise end up with two copies.
  const template = !o.server && fs.existsSync(shellPath)
    ? fs.readFileSync(shellPath, 'utf8').replace(/<script\s+type=["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>\s*/gi, '') : null;

  const browser = await chromium.launch();
  const page = await browser.newPage();
  if (!o.server) {
    await page.route(ORIGIN + '/**', route => {
      const req = route.request(), u = new URL(req.url());
      let f = path.join(o.root, decodeURIComponent(u.pathname));
      if (!f.startsWith(o.root)) return route.fulfill({ status: 403, body: '' });
      if (fs.existsSync(f) && fs.statSync(f).isDirectory()) f = path.join(f, 'index.html');
      // Every page renders from the template shell, never from a previously generated file.
      if (req.resourceType() === 'document' && template != null) return route.fulfill({ status: 200, contentType: 'text/html', body: template });
      if (!fs.existsSync(f)) return route.fulfill({ status: 404, body: '' });
      route.fulfill({ status: 200, contentType: TYPES[path.extname(f).toLowerCase()] || 'application/octet-stream', body: fs.readFileSync(f) });
    });
  }
  let errors = [];
  page.on('pageerror', e => errors.push(e.message));

  const snapshot = async route => {
    errors = [];
    await page.goto(ORIGIN + route, { waitUntil: 'networkidle' });
    if (o.waitFor) await page.waitForSelector(o.waitFor, { timeout: 15000 });
    const res = await page.evaluate(sel => {
      const robots = (document.querySelector('meta[name=robots]') || {}).content || '';
      const canonical = (document.querySelector('link[rel=canonical]') || {}).href || '';
      const links = [...document.querySelectorAll('a[href]')].map(a => a.href);
      const seo = [...document.head.querySelectorAll('title, meta[name=description], meta[name=robots], link[rel=canonical], meta[property^="og:"], meta[property^="profile:"], meta[property^="article:"], meta[name^="twitter:"], script[type="application/ld+json"]')]
        .map(e => e.outerHTML).filter((h, i, all) => all.indexOf(h) === i).join('\n');
      const el = sel ? document.querySelector(sel) : null;
      return { robots, canonical, links, seo, title: document.title, inner: el ? el.innerHTML : null,
        html: '<!doctype html>\n' + document.documentElement.outerHTML };
    }, o.rootSelector || null);
    if (errors.length) throw new Error(route + ': script error while rendering: ' + errors.join('; '));
    if (o.rootSelector && res.inner == null) throw new Error(route + ': ' + o.rootSelector + ' not found');
    return res;
  };

  // Route list: given, or discovered breadth-first from "/" through same-origin links.
  const queue = o.routes ? [...o.routes] : ['/'], seen = new Set(queue), done = [];
  while (queue.length) {
    const route = queue.shift();
    const r = await snapshot(route);
    let out;
    if (o.rootSelector && template) {
      // Put the rendered app root into the template, between <!-- prerender:start --> and <!-- prerender:end --> markers if
      // present, else into the empty root element. No whitespace inside it: hydration matches child nodes one for one.
      const id = o.rootSelector.replace(/^#/, ''), root = `<div id="${id}">${r.inner}</div>`;
      const a = template.indexOf('<!-- prerender:start -->'), z = template.indexOf('<!-- prerender:end -->');
      const empty = new RegExp(`<div id=["']${id}["']>\\s*</div>`);
      if (a >= 0 && z > a) out = template.slice(0, a + 24) + root + template.slice(z);
      else if (empty.test(template)) out = template.replace(empty, () => root);
      else throw new Error(`template needs <!-- prerender:start --><div id="${id}"></div><!-- prerender:end --> or an empty <div id="${id}"></div>`);
      // Replace the template's SEO tags with the ones the app set for this route (title, meta, canonical, OG, Twitter, JSON-LD).
      out = out.replace(/<title>[\s\S]*?<\/title>\s*/i, '')
        .replace(/<meta\s+(?:name|property)=["'](?:description|robots|og:[^"']*|profile:[^"']*|article:[^"']*|twitter:[^"']*)["'][^>]*>\s*/gi, '')
        .replace(/<link\s+rel=["']canonical["'][^>]*>\s*/gi, '')
        .replace(/<script\s+type=["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>\s*/gi, '')
        .replace(/<\/head>/i, () => r.seo + '\n</head>');
    } else out = r.html;
    if (route !== '/') out = out.replace(/^<!doctype html>\n?/i, m => m.trimEnd() + '\n' + GENERATED + '\n');
    const dest = routeFile(o, route);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    // Unchanged pages keep their previous sitemap lastmod: Google only trusts lastmod that reflects real changes.
    const changed = !fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== out;
    fs.writeFileSync(dest, out);
    done.push({ route, changed, noindex: /noindex/i.test(r.robots), canonical: r.canonical });
    console.log(`Pre-rendered ${route} -> ${path.relative(process.cwd(), dest)} (${out.length} chars, "${r.title}")`);
    if (r.canonical && o.site && r.canonical.replace(/\/$/, '') !== (o.site + route).replace(/\/$/, ''))
      console.warn(`  warning: canonical ${r.canonical} differs from ${o.site + route}`);
    if (!o.routes) for (const href of r.links) {
      const u = new URL(href, ORIGIN);
      if (u.origin !== ORIGIN) continue;
      const p = u.pathname.replace(/\/$/, '') || '/';
      if (seen.has(p) || /\.[a-z0-9]+$/i.test(p) || o.exclude.some(x => p.startsWith(x))) continue;
      seen.add(p); queue.push(p);
    }
  }
  await browser.close();

  if (o.sitemap) {
    if (!o.site) { console.warn('No --site given: sitemap.xml not written'); return; }
    const today = new Date().toISOString().slice(0, 10), prev = {};
    const old = path.join(o.out, 'sitemap.xml');
    if (fs.existsSync(old)) for (const m of fs.readFileSync(old, 'utf8').matchAll(/<loc>([^<]+)<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) prev[m[1]] = m[2];
    const loc = x => o.site + (x.route === '/' ? '/' : x.route);
    const urls = done.filter(x => !x.noindex).map(x => `  <url>\n    <loc>${loc(x)}</loc>\n    <lastmod>${!x.changed && prev[loc(x)] ? prev[loc(x)] : today}</lastmod>\n  </url>`);
    fs.writeFileSync(path.join(o.out, 'sitemap.xml'),
      `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`);
    console.log(`Wrote sitemap.xml with ${urls.length} URLs (${done.length - urls.length} noindex pages left out)`);
  }
})().catch(e => { console.error(e.message || e); process.exit(1); });
